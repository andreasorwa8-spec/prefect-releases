"                  : 'Negotiable'}",
"              </Text>",
"            </View>",
"            <View style={styles.gridItem}>",
"              <Text style={styles.gridLabel}>Deadline</Text>",
"              <Text style={styles.gridValue}>",
"                {job.deadline ? new Date(job.deadline).toLocaleDateString() : 'Rolling'}",
"              </Text>",
"            </View>",
